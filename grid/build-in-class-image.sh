#!/bin/bash
# Build this DragonRadio tree on a node running the GNU Radio 3.10 class image
# (krd26/dragonradio-class-gr310-20261027-v2: Ubuntu 26.04, GCC 15, Python 3.14,
# UHD 3.9.5 cc15d9ce), the same way the image builds its own DragonRadio
# (sdr-lab-class image/gr3.10/build-in-container.sh, stage dragonradio). The
# image's third-party libraries (liquid-dsp, libcorrect, firpm under /usr/local)
# and its extern/ sources are reused; nothing under /usr/local is changed.
#
# Usage: build-in-class-image.sh SRC_DIR [JOBS]
#   SRC_DIR  this tree (e.g. extracted from git archive); built in SRC_DIR/build
# Then run the radio with:
#   VIRTUAL_ENV=SRC_DIR/venv SRC_DIR/build/dragonradio SCRIPT
set -euo pipefail
src=$(realpath "$1"); jobs=${2:-$(nproc)}
image=/usr/local/dragonradio
[ -d "$image/extern" ] || { echo "not the class image: no $image/extern" >&2; exit 2; }
cd "$src"
# Header-only and source dependencies from the image's own tree.
for d in "$image"/extern/*; do
    name=$(basename "$d")
    if [ ! -e "extern/$name" ] || [ -z "$(ls -A "extern/$name" 2>/dev/null)" ]; then
        rm -rf "extern/$name"; ln -s "$d" "extern/$name"
    fi
done
# As the image: the system pybind11 (3.0) instead of the submodule.
sed -i 's|^add_subdirectory(extern/pybind11)|find_package(pybind11 CONFIG REQUIRED)|' CMakeLists.txt
export SETUPTOOLS_SCM_PRETEND_VERSION=0+$(cat COMMIT 2>/dev/null | cut -c1-7 || echo port)
cmake -S . -B build -DCMAKE_BUILD_TYPE=Release -DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
    -DCMAKE_CXX_FLAGS="-include cstdint -include cstdio" -DPython3_EXECUTABLE="$image/venv/bin/python"
make -C build -j "$jobs"
ln -sfn build/dragonradio dragonradio
# A venv for this tree: the image's venv installs its own DragonRadio package as
# an editable install, whose import hook would win over PYTHONPATH. This venv
# sees this tree's package first, then the image venv's third-party packages
# (a .pth path entry, so the image's editable-install hook is not loaded).
py=$("$image/venv/bin/python" -c 'import sys; print(f"python{sys.version_info[0]}.{sys.version_info[1]}")')
rm -rf venv
# virtualenv (as the image), which provides bin/activate_this.py for the radio's embedded Python.
virtualenv -q --system-site-packages -p python3 venv
site=venv/lib/$py/site-packages
echo "$src/python/dragonradio/src" > "$site/00-dragonradio-port.pth"
# setuptools-scm writes dragonradio/version.py when the image pip-installs its
# package; this tree is used in place, so write it here (dragonradio.controller
# imports it).
v=${SETUPTOOLS_SCM_PRETEND_VERSION}
cat > python/dragonradio/src/dragonradio/version.py <<EOF
# file generated by grid/build-in-class-image.sh (as setuptools-scm would)
__version__ = version = '$v'
__version_tuple__ = version_tuple = (0, '${v#0+}')
__commit_id__ = commit_id = None
EOF
"$image/venv/bin/python" -c 'import site; print("\n".join(p for p in site.getsitepackages() if "/usr/local/dragonradio/venv" in p))' > "$site/50-image-venv.pth"
# (dragonradio.config imports the C++ module, which only the radio embeds: locate, don't import)
venv/bin/python -c "import importlib.util as u; o = u.find_spec('dragonradio.config').origin; assert o.startswith('$src'), o; print('venv python package:', o)"
echo "built $(cat COMMIT 2>/dev/null || echo '?') in $src/build; run: VIRTUAL_ENV=$src/venv $src/build/dragonradio SCRIPT"
